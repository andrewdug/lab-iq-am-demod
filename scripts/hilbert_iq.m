%% Фильтр Гильберта, fд = 4 f0 = 1720 МГц: обработка результатов Qucs-S и сравнение вариантов (п. 5-8)
% Читает результаты схем LR2k5_N1_hilbert_{R10,W10,W14,W18}_{TR,AC}.sch (файлы .dat появляются
% рядом со схемой после F2) и сравнивает найденные варианты:
%   R10 - порядок 10, без окна;      W10 - порядок 10, окно Хэмминга;
%   W14 - порядок 14, окно Хэмминга; W18 - порядок 18, окно Хэмминга.
% Результат: таблица в консоли и hilbert_iq_summary.csv, графики hilbert_iq_{afc,hodograph,spectra,iq,demod}.png.
% Обработка - в hilbert_iq_core.m; субдискретизация fд = 40 МГц - в hilbert_iq_D43.m.
% MATLAB R2018b и новее (Signal Processing Toolbox не нужен).

clear; close all;

%% Исходные данные
N    = 1;                                   % номер бригады
P    = struct('f0', (400 + 30 * N) * 1e6, ...  % несущая, Гц
              'Fm', 3 * N * 1e6, ...           % частота модуляции, Гц
              'U0', 1, ...                     % амплитуда несущей, В
              'm', 1, ...                      % коэффициент модуляции
              'tAn', [1e-6, 2e-6]);            % окно спектрального анализа: 3 периода Fм (шаг ДПФ 1 МГц)
filt = struct('tag',   {'R10', 'W10', 'W14', 'W18'}, ...
              'name',  {'порядок 10, без окна', 'порядок 10, Хэмминг', ...
                        'порядок 14, Хэмминг', 'порядок 18, Хэмминг'}, ...
              'order', {10, 10, 14, 18});

%% Обработка
hilbert_iq_core(P, filt, 1);
