def P(text, indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False, italic=False, after=None, size=None):
    p = doc.add_paragraph()
    p.alignment = align
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size:
        r.font.size = Pt(size)
    return p


def F(text):
    return P(text, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, italic=True)


def H(text, lvl=1):
    doc.add_heading(text, lvl)


def B(items):
    for t in items:
        p = doc.add_paragraph(t, style="List Bullet")
