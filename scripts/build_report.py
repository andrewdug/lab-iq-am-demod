def sci(x):
    """Малое число в виде 2,7·10⁻¹²."""
    m, e = f"{x:.1e}".split("e")
    return f"{m.replace('.', ',')}·10" + str(int(e)).translate(str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹"))


def c(x, n=3):
    """Число с десятичной запятой и настоящим минусом."""
    return f"{x:.{n}f}".replace(".", ",").replace("-", "−")


