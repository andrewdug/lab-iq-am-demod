def IMG(name, caption, width=16.5, height=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.space_after = Pt(2)
    p.add_run().add_picture(str(FIG / name), **({"height": Cm(height)} if height else {"width": Cm(width)}))
    fig_no[0] += 1
    P(f"Рисунок {fig_no[0]} — {caption}", indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, size=12, after=10)


def T(header, rows, widths, caption):
    tab_no[0] += 1
    p = P(f"Таблица {tab_no[0]} — {caption}", indent=False, align=WD_ALIGN_PARAGRAPH.LEFT, size=12, after=3)
    p.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate([header] + rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths[j])
            q = cell.paragraphs[0]
            q.alignment = WD_ALIGN_PARAGRAPH.CENTER if j else WD_ALIGN_PARAGRAPH.LEFT
            q.paragraph_format.space_after = Pt(0)
            q.paragraph_format.line_spacing = 1.0
            run = q.add_run(str(val))
            run.font.size = Pt(11)
            run.bold = i == 0
    doc.add_paragraph().paragraph_format.space_after = Pt(4)


