%% Фильтр Гильберта, субдискретизация fд = 4 f0 / 43 = 40 МГц: обработка результатов Qucs-S (п. 5-8)
% Читает результаты схем LR2k5_N1_hilbert_{R10,W10,W18}_D43_{TR,AC}.sch (файлы .dat появляются
% рядом со схемой после F2) и сравнивает найденные варианты:
%   R10 - порядок 10, без окна; W10 - порядок 10, окно Хэмминга; W18 - порядок 18, окно Хэмминга.
% 430 МГц = 10,75 fд, поэтому несущая после дискретизации оказывается на -fд/4 = -10 МГц.
% Результат: таблица в консоли и hilbert_iq_D43_summary.csv,
% графики hilbert_iq_D43_{afc,hodograph,spectra,iq,demod}.png.
% Обработка - в hilbert_iq_core.m; fд = 1720 МГц - в hilbert_iq.m.
% MATLAB R2018b и новее (Signal Processing Toolbox не нужен).

clear; close all;

%% Исходные данные
N    = 1;                                   % номер бригады
div  = 43;                                  % fд = 4 f0 / div
P    = struct('f0', (400 + 30 * N) * 1e6, ...  % несущая, Гц
              'Fm', 3 * N * 1e6, ...           % частота модуляции, Гц
              'U0', 1, ...                     % амплитуда несущей, В
              'm', 1, ...                      % коэффициент модуляции
              'tAn', [1e-6, 2e-6]);            % окно спектрального анализа: 3 периода Fм (шаг ДПФ 1 МГц)
filt = struct('tag',   {'R10', 'W10', 'W18'}, ...
              'name',  {'порядок 10, без окна', 'порядок 10, Хэмминг', 'порядок 18, Хэмминг'}, ...
              'order', {10, 10, 18});

%% Обработка
hilbert_iq_core(P, filt, div);
